import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const code=(await fs.readFile(new URL('../web/api.js',import.meta.url),'utf8')).replaceAll('export ','');
const listeners=new Map(),frames=[],timers=new Set();
const window={addEventListener:(n,fn)=>listeners.set(n,fn),removeEventListener:(n)=>listeners.delete(n)};
const document={createElement:()=>({remove(){this.removed=true;}}),body:{append:f=>frames.push(f)}};
const context=vm.createContext({crypto:webcrypto,Uint8Array,URL,Error,Promise,Map,window,document,setTimeout:(fn,ms)=>{const t=setTimeout(fn,ms);timers.add(t);return t;},clearTimeout:t=>{clearTimeout(t);timers.delete(t);}});
vm.runInContext(code+'\nthis.ClipAPI=ClipAPI;this.validEndpoint=validEndpoint;',context);
assert.equal(context.validEndpoint('https://script.google.com.attacker.example/macros/s/a/exec'),null);
assert.equal(context.validEndpoint('https://script.google.com/macros/s/a/exec?token=secret'),null);
assert.equal(context.validEndpoint('http://script.google.com/macros/s/a/exec'),null);
const api=new context.ClipAPI('https://script.google.com/macros/s/test/exec','a'.repeat(64));
assert.equal(frames.length,1);assert.equal(frames[0].src.includes('token'),false);
let sent;
const source={postMessage:(message,origin)=>{sent={message,origin};}};
const emit=(origin,payload,from=source)=>listeners.get('message')({origin,source:from,data:{namespace:'laterclip',channel:api.channel,...payload}});
emit('https://attacker.example',{type:'ready'});assert.equal(api.source,null);
emit('https://script.googleusercontent.com.attacker.example',{type:'ready'});assert.equal(api.source,null);
emit('https://script.googleusercontent.com',{type:'ready',channel:'wrong'});assert.equal(api.source,null);
emit('https://script.googleusercontent.com',{type:'ready'});await api.ready;
const pending=api.request('list');await new Promise(resolve=>setImmediate(resolve));
assert.equal(sent.origin,'https://script.googleusercontent.com');assert.equal(sent.message.payload.token,'a'.repeat(64));
emit('https://script.googleusercontent.com',{type:'response',id:sent.message.id,result:{ok:true,clips:['spoof']}},{});
assert.equal(api.pending.size,1);
emit('https://script.googleusercontent.com',{type:'response',id:sent.message.id,result:{ok:true,clips:[]}});
assert.equal((await pending).clips.length,0);
api.close();assert.equal(api.token,'');assert.equal(listeners.size,0);assert.equal(frames[0].removed,true);
for(const t of timers)clearTimeout(t);
console.log('PASS: endpoint validation, no secret in URL, source/origin/channel validation, response correlation, secret cleanup');
