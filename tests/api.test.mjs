import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
const code=(await fs.readFile(new URL('../web/api.js',import.meta.url),'utf8')).replaceAll('export ','');
let sent, respond=async()=>({ok:true,json:async()=>({ok:true,clips:[]})});
const context=vm.createContext({URL,Error,TypeError,JSON,Set,AbortController,setTimeout,clearTimeout,fetch:async(url,options)=>{sent={url,options};return respond(options);}});
vm.runInContext(code+'\nthis.ClipAPI=ClipAPI;this.validEndpoint=validEndpoint;',context);
assert.equal(context.validEndpoint('https://script.google.com.attacker.example/macros/s/a/exec'),null);
assert.equal(context.validEndpoint('https://script.google.com/macros/s/a/exec?token=secret'),null);
assert.equal(context.validEndpoint('http://script.google.com/macros/s/a/exec'),null);
const endpoint='https://script.google.com/macros/s/test/exec',token='a'.repeat(64);
const api=new context.ClipAPI(endpoint,token);
assert.equal((await api.request('list',{includeArchived:true,token:'override'})).clips.length,0);
assert.equal(sent.url,endpoint);assert.equal(sent.url.includes(token),false);
assert.equal(sent.options.credentials,'omit');assert.equal(sent.options.mode,'cors');
assert.equal(sent.options.headers['Content-Type'],'text/plain;charset=UTF-8');
assert.deepEqual(JSON.parse(sent.options.body),{includeArchived:true,token,action:'list'});
respond=async()=>({ok:true,json:async()=>({ok:false,error:'인증 테스트'})});
await assert.rejects(api.request('list'),/인증 테스트/);
respond=async()=>({ok:true,json:async()=>{throw Error('html');}});
await assert.rejects(api.request('list'),/서버 응답/);
respond=async()=>({ok:false});await assert.rejects(api.request('list'),/서버에 연결/);
respond=options=>new Promise((_,reject)=>options.signal.addEventListener('abort',()=>reject(Error('aborted'))));
const pending=api.request('archive',{id:'example'});assert.equal(api.pending.size,1);
api.close();await assert.rejects(pending,/연결이 종료/);
assert.equal(api.token,'');assert.equal(api.pending.size,0);
await assert.rejects(api.request('list'),/연결이 종료/);
console.log('PASS: strict endpoint validation, key only in body, cookie-free simple CORS, API errors, invalid responses, cancellation and secret cleanup');
